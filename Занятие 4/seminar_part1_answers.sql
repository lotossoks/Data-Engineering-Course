-- 3. Угадай план: индекс из двух столбцов (customer_id, order_created_at)
--
-- Главная мысль: такой индекс похож на телефонный справочник,
-- отсортированный по фамилии, а внутри фамилии — по имени.
-- Найти «Иванова Петра» легко, найти всех Иванов, не зная фамилии, — нельзя.
-- ---------------------------------------------------------------------

-- 3.1 Индекс ПОМОГАЕТ. Bitmap Index Scan on idx_orders_big_customer_created,
--     оба условия в Index Cond, 12 строк, доли миллисекунды.

-- 3.2 Индекс НЕ помогает: Parallel Seq Scan, Rows Removed by Filter: ~1,7 млн
--     на каждый из 3 процессов, ~50 мс. Дата — второй столбец индекса,
--     а без первого (customer_id) по индексу искать нельзя.
--     Чтобы ускорить, нужен отдельный индекс, где дата стоит первой.

-- 3.3 Индекс НЕ помогает: Parallel Seq Scan, ~90 мс, хотя клиент тот же,
--     что в 3.1. Индекс хранит числа customer_id, а запрос ищет текст
--     customer_id::text. Любая функция или приведение типа над столбцом
--     отключают обычный индекс по этому столбцу.
--     Как исправить: where customer_id = 4217.

-- 3.4 Индекс помогает ЧАСТИЧНО. Index Cond: (customer_id = 4217) —
--     индекс нашёл 108 заказов клиента. Filter: (order_created_at)::date = ...
--     и Rows Removed by Filter: 108 — дату проверили уже на прочитанных строках.
--     Причина та же, что в 3.3: ::date — это приведение типа над столбцом.

-- 3.5 Ответ: заменить «дату» на диапазон времени.
explain analyze
select order_id, total_amount from orders_big
where customer_id = 4217
  and order_created_at >= '2026-05-15'
  and order_created_at <  '2026-05-16';
-- Index Scan, все три условия в Index Cond, Filter нет.
-- (Заказов за этот день у клиента нет — 0 строк, это нормально.)


-- ---------------------------------------------------------------------
-- 4. Отчёт, который не читает таблицу (Index Only Scan)
-- ---------------------------------------------------------------------

-- 4.1 Bitmap Index Scan по индексу из задания 2, затем Bitmap Heap Scan:
--     126 900 строк, Heap Blocks ~650–970. Индекс знает customer_id,
--     но не знает total_amount, поэтому база идёт за суммой в таблицу.

-- 4.2 Ответ:
create index idx_orders_big_customer_amount
    on orders_big (customer_id) include (total_amount);
-- INCLUDE кладёт total_amount в индекс «пассажиром»: по нему не ищут,
-- но его можно прочитать прямо из индекса.

-- 4.3 План НЕ меняется — это главный сюрприз задания.
--     Таблица создана с autovacuum_enabled = false, и VACUUM по ней ни разу
--     не запускался. Index Only Scan может не ходить в таблицу, только если
--     знает, что страница таблицы «чистая» (все строки на ней видны всем).
--     Эти отметки ставит VACUUM в карте видимости (visibility map).
--     Пока карта пустая, планировщик понимает, что ходить в таблицу всё равно
--     придётся за каждой строкой, и Index Only Scan не выбирает.

-- 4.4 После VACUUM: Parallel Index Only Scan using idx_orders_big_customer_amount,
--     Heap Fetches: 0 — ни одного обращения к таблице.
--     Heap Fetches = сколько раз база всё-таки сходила в таблицу,
--     потому что страница не была отмечена как чистая.
--     Осторожно: заметного выигрыша во времени здесь нет (13 мс → 12 мс):
--     нужные строки и так лежат в таблице рядом. Смысл задания — тип плана
--     и роль VACUUM, а не скорость. В обычной базе VACUUM запускает
--     автоматический процесс autovacuum, здесь мы его отключили специально.


-- ---------------------------------------------------------------------
-- 5. Очередь заказов «в ожидании» (частичный индекс)
-- ---------------------------------------------------------------------

-- 5.1 Bitmap Index Scan по status находит все 396 000 заказов pending,
--     Bitmap Heap Scan читает их из таблицы (Buffers ~37 000 страниц ≈ 290 МБ,
--     почти вся таблица), потом Sort выбирает 50 самых старых. ~60–120 мс.
--     Чтобы показать 50 строк, база прочитала 396 000.

-- 5.2 Ответ:
create index idx_orders_big_pending_created
    on orders_big (order_created_at)
    where status = 'pending';

-- 5.3 Index Scan using idx_orders_big_pending_created, Sort исчез:
--     строки в индексе уже лежат по дате, база берёт первые 50 и останавливается.
--     Buffers ~50 страниц вместо ~37 000, время ~0,2 мс вместо ~60 мс.
--     Index Cond в плане нет: условие status = 'pending' зашито в сам индекс.

-- 5.4 Новый индекс ~3 МБ, индекс по status — 34 МБ, первичный ключ — 109 МБ.
--     В частичный индекс попали только 396 000 строк pending (7,8% таблицы),
--     а не все 5 млн. Меньше места на диске и дешевле вставка остальных строк.

-- 5.5 НЕ поможет: снова Bitmap Heap Scan + Sort, ~50 мс.
--     В индексе есть только строки pending, строк cancelled там нет.
--     Частичный индекс подходит для одного частого запроса с постоянным условием
--     (очередь, «активные», «неудалённые»), а не для фильтра «любой статус».
--     Для любого статуса нужен обычный индекс (status, order_created_at),
--     он тоже ускорит 5.1, но весит 37 МБ.
